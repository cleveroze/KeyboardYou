/** Недавние, избранные эмодзи и поиск по ключевым словам (Unicode CLDR, ru + en). */
object EmojiStore {
    private const val RECENT_LIMIT = 15
    private lateinit var prefs: android.content.SharedPreferences
    private val _recents = kotlinx.coroutines.flow.MutableStateFlow<List<String>>(emptyList())
    private val _favorites = kotlinx.coroutines.flow.MutableStateFlow<List<String>>(emptyList())
    val recents: kotlinx.coroutines.flow.StateFlow<List<String>> = _recents
    val favorites: kotlinx.coroutines.flow.StateFlow<List<String>> = _favorites

    @Volatile
    private var keywords: List<Pair<String, List<String>>>? = null

    fun init(context: Context) {
        if (::prefs.isInitialized) return
        val app = context.applicationContext
        prefs = app.getSharedPreferences("emoji", Context.MODE_PRIVATE)
        _recents.value = prefs.getString("recent", "")!!.split(' ').filter { it.isNotBlank() }.take(RECENT_LIMIT)
        _favorites.value = prefs.getString("favorites", "")!!.split(' ').filter { it.isNotBlank() }
        Thread {
            runCatching {
                keywords = app.assets.open("emoji_keywords.tsv").bufferedReader().readLines().mapNotNull { line ->
                    val tab = line.indexOf('\t')
                    if (tab <= 0) null else line.substring(0, tab) to line.substring(tab + 1).split('|').filter { it.isNotBlank() }
                }
            }
        }.apply { isDaemon = true }.start()
    }

    fun use(emoji: String) {
        val list = (listOf(emoji) + _recents.value.filter { it != emoji }).take(RECENT_LIMIT)
        _recents.value = list
        if (::prefs.isInitialized) prefs.edit().putString("recent", list.joinToString(" ")).apply()
    }

    fun isFavorite(emoji: String) = emoji in _favorites.value

    fun toggleFavorite(emoji: String) {
        val list = if (isFavorite(emoji)) _favorites.value - emoji else listOf(emoji) + _favorites.value
        _favorites.value = list
        if (::prefs.isInitialized) prefs.edit().putString("favorites", list.joinToString(" ")).apply()
    }

    /** Поиск: точное совпадение слова > начало слова > вхождение. */
    fun search(query: String, limit: Int = 60): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        val data = keywords ?: return emptyList()
        val scored = ArrayList<Pair<String, Int>>()
        data.forEachIndexed { index, (emoji, words) ->
            var best = 0
            for (w in words) {
                val s = when {
                    w == q -> 4
                    w.startsWith(q) -> 3
                    w.split(' ', '-').any { it.startsWith(q) } -> 2
                    q.length >= 3 && w.contains(q) -> 1
                    else -> 0
                }
                if (s > best) best = s
                if (best == 4) break
            }
            if (best > 0) scored += emoji to (best * 100_000 - index)
        }
        return scored.sortedByDescending { it.second }.take(limit).map { it.first }
    }
}
